"""Independent UCUB-001 human annotation tooling.

No semantic labels are generated by a parser or an LLM here. The script
supplies blinded prompts and checks evidence submitted by two distinct,
self-declared independent human reviewers. Reviewer independence cannot be
verified by software; curators must check that outside the repository.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter
from pathlib import Path
from typing import Any

from .runner import LABELS, load_corpus

REVIEW_SCHEMA = "unisermo/ucub001-human-review@1"
REPORT_SCHEMA = "unisermo/ucub001-review-aggregate@1"
EXACT_KEYS = ("id", "label", "own_translation", "english_equivalence",
              "confidence", "rationale", "ambiguity")
EQ = {"equivalent", "not_equivalent", "uncertain"}
LABEL_CHOICES = LABELS | {"uncertain"}


def _json_lines(rows: list[dict]) -> str:
    return "".join(json.dumps(r, ensure_ascii=False, sort_keys=True,
                              separators=(",", ":")) + "\n" for r in rows)


def make_packet(stage: str, *, split: str = "all") -> tuple[str, dict[str, Any]]:
    """Blind the author gold and test/holdout status in BOTH review phases."""
    if stage not in ("semantic", "equivalence"):
        raise ValueError("unknown review stage")
    if split not in ("all", "development", "holdout"):
        raise ValueError("invalid split")
    rows, manifest = load_corpus()
    selected = [r for r in rows if split == "all" or r["split"] == split]
    packet = []
    for r in selected:
        item = {"id": r["id"], "level": r["level"],
                "unisermo": r["unisermo"], "hypothesis": r["hypothesis"]}
        if stage == "equivalence":
            item["draft_english"] = r["english"]
        packet.append(item)
    payload = _json_lines(packet)
    info = {"schema": "unisermo/ucub001-blind-review-packet@1",
            "stage": stage, "count": len(packet),
            "split_scope": split, "corpus_sha256": manifest["corpus_sha256"],
            "packet_sha256": hashlib.sha256(payload.encode("utf-8")).hexdigest(),
            "gold_visible": False, "source_split_visible": False,
            "note": ("Human reviewers must independently translate and label the "
                     "semantic-stage packet BEFORE viewing the equivalence-stage "
                     "draft English. The original gold is not shown.")}
    return payload, info


def validate_review_file(path: Path, *, expected_ids: set[str],
                         corpus_sha256: str) -> dict:
    """Check a reviewer's complete 80-item declaration, not their expertise."""
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("schema") != REVIEW_SCHEMA:
        raise ValueError("invalid human review schema")
    if data.get("corpus_sha256") != corpus_sha256:
        raise ValueError("review was prepared against another corpus revision")
    identity = data.get("reviewer_id")
    if not isinstance(identity, str) or not 3 <= len(identity.strip()) <= 128:
        raise ValueError("reviewer_id required; use a stable distinct identifier")
    if data.get("review_method") != "human":
        raise ValueError("human attestations only; model audits are separate")
    if data.get("independent_of_corpus_author") is not True:
        raise ValueError("explicit declaration of independence required")
    if not isinstance(data.get("reviewed_at_utc"), str) or len(data["reviewed_at_utc"]) < 10:
        raise ValueError("review completion timestamp required")
    answers = data.get("annotations")
    if not isinstance(answers, list) or len(answers) != len(expected_ids):
        raise ValueError("one complete annotation per reviewed item is mandatory")
    seen = {}
    for x in answers:
        if not isinstance(x, dict) or set(x) != set(EXACT_KEYS):
            raise ValueError("review annotation shape invalid")
        case_id = x["id"]
        if not isinstance(case_id, str) or case_id in seen or case_id not in expected_ids:
            raise ValueError("unknown or repeated case id")
        if x["label"] not in LABEL_CHOICES:
            raise ValueError("invalid semantic label")
        if x["english_equivalence"] not in EQ:
            raise ValueError("invalid English equivalence assessment")
        if isinstance(x["confidence"], bool) or x["confidence"] not in (1, 2, 3, 4, 5):
            raise ValueError("invalid confidence")
        for key in ("own_translation", "rationale", "ambiguity"):
            if not isinstance(x[key], str):
                raise ValueError("review text field must be a string")
        if not x["own_translation"].strip() or not x["rationale"].strip():
            raise ValueError("every annotation needs a personal translation and rationale")
        seen[case_id] = x
    if set(seen) != expected_ids:
        raise ValueError("review is incomplete")
    return data


def summarize_review(review_a: dict, review_b: dict, rows: list[dict], digest: str) -> dict:
    if review_a["reviewer_id"] == review_b["reviewer_id"]:
        raise ValueError("two distinct reviewers required")
    aa = {x["id"]: x for x in review_a["annotations"]}
    bb = {x["id"]: x for x in review_b["annotations"]}
    report_items, tally = [], Counter()
    for case in rows:
        a, b = aa[case["id"]], bb[case["id"]]
        labels_agree = a["label"] == b["label"] and a["label"] in LABELS
        translated_agree = (a["english_equivalence"] == "equivalent"
                            and b["english_equivalence"] == "equivalent")
        ambiguity_free = not a["ambiguity"].strip() and not b["ambiguity"].strip()
        confident = a["confidence"] >= 3 and b["confidence"] >= 3
        if labels_agree and translated_agree and ambiguity_free and confident:
            status = ("agreed_draft_gold" if a["label"] == case["gold"]
                      else "agreed_but_draft_gold_disputed")
        else:
            status = "requires_adjudication"
        tally[status] += 1
        report_items.append({
            "id": case["id"], "level": case["level"], "split": case["split"],
            "family": case["family"], "status": status,
            "draft_gold": case["gold"],
            "review_labels": [a["label"], b["label"]],
            "review_equivalence": [a["english_equivalence"], b["english_equivalence"]],
            "review_confidence": [a["confidence"], b["confidence"]],
            "ambiguity_reports": [a["ambiguity"], b["ambiguity"]],
            "reviewers_agree_on_label": labels_agree,
        })
    return {"schema": REPORT_SCHEMA, "corpus_sha256": digest,
            "reviewers": [review_a["reviewer_id"], review_b["reviewer_id"]],
            "human_independence": "self_attested_not_technically_verified",
            "number_of_cases": len(rows), "counts": dict(tally),
            "needs_adjudication": sum(x["status"] != "agreed_draft_gold" for x in report_items),
            "status": ("awaiting_formal_signoff" if all(x["status"] == "agreed_draft_gold" for x in report_items)
                       else "incomplete_or_disputed"),
            "items": report_items}


def _write_new(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8") as handle:
        handle.write(content)


def main() -> None:
    p = argparse.ArgumentParser(description="Independent semantic and translation review, no LLM calls")
    sub = p.add_subparsers(dest="action", required=True)
    packets = sub.add_parser("packet")
    packets.add_argument("--stage", required=True, choices=("semantic", "equivalence"))
    packets.add_argument("--split", default="all", choices=("all", "development", "holdout"))
    packets.add_argument("--output", type=Path, required=True)
    starter = sub.add_parser("init")
    starter.add_argument("--reviewer-id", required=True)
    starter.add_argument("--output", type=Path, required=True)
    aggregate = sub.add_parser("aggregate")
    aggregate.add_argument("--review-a", type=Path, required=True)
    aggregate.add_argument("--review-b", type=Path, required=True)
    aggregate.add_argument("--output", type=Path, required=True)
    args = p.parse_args()
    if args.action == "packet":
        payload, info = make_packet(args.stage, split=args.split)
        _write_new(args.output, payload)
        _write_new(args.output.with_suffix(args.output.suffix + ".manifest.json"),
                   json.dumps(info, indent=2, ensure_ascii=False, sort_keys=True) + "\n")
        print(f"Blinded {args.stage} review packet: {info['count']} items, no gold")
        return
    if args.action == "init":
        rows, manifest = load_corpus()
        content = {
            "schema": REVIEW_SCHEMA,
            "corpus_sha256": manifest["corpus_sha256"],
            "reviewer_id": args.reviewer_id,
            "review_method": "human",
            "independent_of_corpus_author": False,
            "reviewed_at_utc": "",
            "annotations": [
                {"id": r["id"], "label": "uncertain", "own_translation": "",
                 "english_equivalence": "uncertain", "confidence": 1,
                 "rationale": "", "ambiguity": ""}
                for r in rows
            ],
        }
        _write_new(args.output, json.dumps(content, indent=2, ensure_ascii=False, sort_keys=True) + "\\n")
        print("Created BLANK review form for", len(rows),
              "cases; it is NOT an attestation or completed review")
        return
    rows, manifest = load_corpus()
    ids = {r["id"] for r in rows}
    reviews = [validate_review_file(path, expected_ids=ids,
                                     corpus_sha256=manifest["corpus_sha256"])
               for path in (args.review_a, args.review_b)]
    report = summarize_review(reviews[0], reviews[1], rows, manifest["corpus_sha256"])
    _write_new(args.output, json.dumps(report, indent=2, ensure_ascii=False, sort_keys=True) + "\n")
    print("Two-human preliminary review:", report["counts"], "-",
          report["status"], "(independence self-attested)")


if __name__ == "__main__":
    main()
