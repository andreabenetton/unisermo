"""Deterministic finite morphology, nominal morphology and restricted SVO clause parsing.

No probabilistic guesses and no automatic ratification of documentary examples.
The data index is generated by `python -m formalization build`.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "formalization" / "data"


def load(name: str) -> dict:
    return json.loads((DATA / name).read_text(encoding="utf-8"))


from .generator.morphology import MorphologyGenerator
from .parser.word import WordParser
from .parser.clause import ClauseParser


class Unisermo(MorphologyGenerator, WordParser, ClauseParser):
    def __init__(self) -> None:
        self.morph = load("morphology.json")
        index = load("lexicon_index.json")
        self.lexicon = {entry["form"]: entry for entry in index["entries"]}
        self.verbs = {form for form, entry in self.lexicon.items() if "verb" in entry["categories"]}
        self.nouns = {form for form, entry in self.lexicon.items()
                      if "noun" in entry["categories"] or "nominal_predicate" in entry["categories"]}
        self.person_to_form = {("singular", 1): "i", ("singular", 2): "u", ("singular", 3): "a",
                               ("plural", 1): "in", ("plural", 2): "un", ("plural", 3): "an"}
        self.pronoun_to_person = {v: k for k, v in self.person_to_form.items()}
        self.demonstratives = {form for form, entry in self.lexicon.items() if "demonstrative" in entry["categories"]}
        self.quantifiers = {form for form, entry in self.lexicon.items() if "quantifier" in entry["categories"]}

